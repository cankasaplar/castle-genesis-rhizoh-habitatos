  "# Ingress: legal + cohort (rhizoh.com); explicit=1 so .env.local cannot disable on deploy",
  "VITE_RHIZOH_LEGAL_PREAMBLE=1",
  "VITE_RHIZOH_CLOSED_ADMISSION=1",
  "VITE_RHIZOH_INVITE_ONLY_GOOGLE=1",
