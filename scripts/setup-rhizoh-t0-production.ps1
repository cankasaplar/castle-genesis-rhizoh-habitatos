  "# Voice Engine v3 - MediaRecorder + gateway Whisper/Google STT",
  "VITE_RHIZOH_VOICE_ENGINE_V3=1",
  "VITE_RHIZOH_VOICE_WITNESS_SHADOW=1",
  "VITE_RHIZOH_VOICE_ATTENTION_MODE=moving_context",
