#!/usr/bin/env node
/**
 * Materialize apps/client/.env.production from process.env (GitHub Actions secrets)
 * merged with spatial-main defaults (Serencebey origin seed + voice stack).
 * Run before validate + vite build so both read the same baked keys.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  RHIZOH_PROD_ENV_KEYS_V0,
  resolveRhizohProdEnvValueV0
} from "./rhizoh-spatial-main-prod-profile.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(root, "apps", "client", ".env.production");

/** @type {string[]} */
const lines = [
  "# Generated by write-rhizoh-client-prod-env-ci.mjs — do not commit",
  "# Profile: spatial-main (Serencebey origin seed + cohort voice stack)"
];
let written = 0;

for (const key of RHIZOH_PROD_ENV_KEYS_V0) {
  const value = resolveRhizohProdEnvValueV0(key);
  if (value == null) continue;
  lines.push(`${key}=${value}`);
  written += 1;
}

if (written === 0) {
  console.warn("[rhizoh-prod-env] No VITE_* keys resolved — .env.production not written");
  process.exit(0);
}

mkdirSync(dirname(envPath), { recursive: true });
writeFileSync(envPath, `${lines.join("\n")}\n`, "utf8");
console.log(`[rhizoh-prod-env] Wrote apps/client/.env.production (${written} keys, spatial-main profile)`);
