#!/usr/bin/env node
/**
 * Materialize apps/client/.env.production from process.env (GitHub Actions secrets).
 * Run before validate + vite build so both read the same baked keys.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(root, "apps", "client", ".env.production");

const KEYS = [
  "VITE_GATEWAY_TOKEN",
  "VITE_GATEWAY_HTTP",
  "VITE_RHIZOH_LLM_HTTP",
  "VITE_LIVE_GATEWAY_BASE",
  "VITE_GATEWAY_URL",
  "VITE_GATEWAY_WS",
  "VITE_GATEWAY_WS_URL",
  "VITE_FIREBASE_CONFIG",
  "VITE_FIREBASE_API_KEY",
  "VITE_FIREBASE_AUTH_DOMAIN",
  "VITE_FIREBASE_PROJECT_ID",
  "VITE_FIREBASE_STORAGE_BUCKET",
  "VITE_FIREBASE_MESSAGING_SENDER_ID",
  "VITE_FIREBASE_APP_ID",
  "VITE_FIREBASE_MEASUREMENT_ID",
  "VITE_FIREBASE_DATABASE_URL",
  "VITE_ENV",
  "VITE_CASTLE_APP_ID",
  "VITE_GENESIS_DEPLOY_MODE",
  "VITE_RHIZOH_VOICE_ENGINE_V3",
  "VITE_RHIZOH_VOICE_WITNESS_SHADOW",
  "VITE_RHIZOH_STT_LANGUAGE",
  "VITE_RHIZOH_VOICE_ENV_PROFILE"
];

/** @type {string[]} */
const lines = ["# Generated by write-rhizoh-client-prod-env-ci.mjs — do not commit"];
let written = 0;

for (const key of KEYS) {
  const raw = process.env[key];
  if (raw == null) continue;
  const v = String(raw).trim();
  if (!v) continue;
  lines.push(`${key}=${v}`);
  written += 1;
}

if (written === 0) {
  console.warn("[rhizoh-prod-env] No VITE_* keys in process.env — .env.production not written");
  process.exit(0);
}

mkdirSync(dirname(envPath), { recursive: true });
writeFileSync(envPath, `${lines.join("\n")}\n`, "utf8");
console.log(`[rhizoh-prod-env] Wrote apps/client/.env.production (${written} keys)`);
